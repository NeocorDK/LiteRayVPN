export type Lang = "ru" | "en";
export const dictionaries: Record<Lang, Record<Key, string>> = { ru, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Maps backend error codes ("PORT_BUSY:10808", "NEED_ADMIN") to text; other errors pass through. */
export function translateError(lang: Lang, err: unknown): string {
  const msg = String(err);
  const [code, arg] = msg.split(":", 2);
  const key = `err.${code}` as Key;
  if (key in dictionaries[lang]) return translate(lang, key, { p: arg ?? "" });
  return msg;
}

export type { Key };
